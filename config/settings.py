"""
Settings for the Loyal Green factory system.

The laptop runs with SQLite and DEBUG on by default. The server sets the
environment variables below (see .env.example) to switch to PostgreSQL.
"""

import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def env_bool(name, default=False):
    return os.environ.get(name, str(default)).lower() in ("1", "true", "yes")


